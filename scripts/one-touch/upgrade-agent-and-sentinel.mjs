#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';

function ensureDir(d){ if(!fs.existsSync(d)) fs.mkdirSync(d,{recursive:true}); }
function writeFileAtomic(p,content){
  const dir = path.dirname(p); ensureDir(dir);
  if(fs.existsSync(p)){
    const bak = p + '.bak.' + Date.now();
    fs.copyFileSync(p, bak);
    console.log('• backup', bak);
  }
  fs.writeFileSync(p, content, 'utf8');
  console.log('✓ wrote', p);
}
function updatePackageJson(){
  const pjPath = 'package.json';
  const raw = fs.readFileSync(pjPath,'utf8');
  const pj = JSON.parse(raw);
  pj.scripts = pj.scripts || {};
  pj.scripts['agent:run'] = 'node scripts/agent/runner.mjs';
  pj.scripts['validate:opening'] = 'node scripts/verify-opening.mjs';
  fs.writeFileSync(pjPath, JSON.stringify(pj, null, 2) + '\n', 'utf8');
  console.log('✓ updated package.json scripts (agent:run, validate:opening)');
}

