#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import opentype from 'opentype.js';
import { optimize } from 'svgo';

const TEXT = 'HELLO CURTIS';
const FONT_PATH = path.resolve('src/assets/fonts/CourierPrime-Regular.ttf');
const FONT_SIZE = 180;
const LETTER_SPACING = 8;
const BASELINE_Y = 0;
const PRECISION = 3;

const OUT_JS = path.resolve('src/assets/paths/hello-curtis-d.js');
const EXPORT_NAME = 'HELLO_CURTIS_PATH_D';

function toFixed(n, p=3){ return Number.parseFloat(n).toFixed(p); }
function pathToSvgD(cmds, precision){
  let d=''; for (const c of cmds){
    if (c.type==='M') d+=`M${toFixed(c.x,precision)},${toFixed(c.y,precision)} `;
    else if (c.type==='L') d+=`L${toFixed(c.x,precision)},${toFixed(c.y,precision)} `;
    else if (c.type==='C') d+=`C${toFixed(c.x1,precision)},${toFixed(c.y1,precision)} ${toFixed(c.x2,precision)},${toFixed(c.y2,precision)} ${toFixed(c.x,precision)},${toFixed(c.y,precision)} `;
    else if (c.type==='Q') d+=`Q${toFixed(c.x1,precision)},${toFixed(c.y1,precision)} ${toFixed(c.x,precision)},${toFixed(c.y,precision)} `;
    else if (c.type==='Z') d+='Z ';
  } return d.trim();
}

(async ()=>{
  if (!fs.existsSync(FONT_PATH)) {
    console.error('Font not found at', FONT_PATH);
    process.exit(1);
  }
  const font = await opentype.load(FONT_PATH);

  let x=0; const parts=[];
  for (const ch of TEXT){
    const glyph = font.charToGlyph(ch);
    const gp = glyph.getPath(x, BASELINE_Y, FONT_SIZE);
    parts.push(pathToSvgD(gp.commands, PRECISION));
    x += glyph.advanceWidth * (FONT_SIZE / font.unitsPerEm) + LETTER_SPACING;
  }
  let dMerged = parts.join(' ');
  const svg = `<svg xmlns="http://www.w3.org/2000/svg"><path d="${dMerged}"/></svg>`;
  const { data } = optimize(svg, { multipass:true, floatPrecision:PRECISION });
  const m = data.match(/ d="([^"]+)"/);
  const finalD = m ? m[1] : dMerged;

  const js = `// auto-generated by scripts/make-hello-curtis-path.mjs\nexport const ${EXPORT_NAME} = ${JSON.stringify(finalD)};\n`;
  fs.mkdirSync(path.dirname(OUT_JS), { recursive:true });
  fs.writeFileSync(OUT_JS, js, 'utf8');
  console.log('Wrote', OUT_JS);
})();
