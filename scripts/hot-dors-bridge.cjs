#!/usr/bin/env node
/* eslint-env node */
/**
 * HOT-DORS Bridge (redo)
 * - Atomic → BeatBus (stage + morph)
 * - Morph shim + global scroll→morph sync
 * - StateCore init (one-time)
 * - EventValidator (no React hooks)
 * - Atoms Doctor + sprint-recorder.sh helper
 * - Package.json scripts (hot-dors:bridge, doctor:atoms, doctor:all)
 * - Backups + report under doctor_artifacts/
 */
const fs = require('fs');
const _path = require('path');
const CWD = process.cwd();
const OUT_DIR = path.join(CWD, 'doctor_artifacts');
fs.mkdirSync(OUT_DIR, { recursive: true });
const report = { changed: [], created: [], skipped: [], errors: [], notes: [] };

const ts = () => new Date().toISOString().replace(/[:.]/g,'-');
const ensureDir = (p) => fs.mkdirSync(path.dirname(p), { recursive: true });

function writeFileBacked(file, content, mode='change') {
  ensureDir(file);
  if (fs.existsSync(file)) {
    const orig = fs.readFileSync(file, 'utf8');
    if (orig === content) { report.skipped.push(file); return false; }
    const bak = file + '.bak.' + ts();
    fs.writeFileSync(bak, orig);
    report.changed.push({ file, backup: bak, mode });
  } else {
    report.created.push(file);
  }
  fs.writeFileSync(file, content);
  return true;
}
function read(file) { try { return fs.readFileSync(file, 'utf8'); } catch { return null; } }

/* 1) Atomic → BeatBus bridge */
function ensureAtomicToBeatBus() {
  const file = path.join(CWD, 'modules/state/bridges/AtomicToBeatBus.js');
  const content =
`// AUTO-GENERATED by HOT-DORS Bridge — AtomicToBeatBus
import BeatBus from '@/theater/bus';
import { EVENTS } from '@/theater/events.js';
import { stageAtom } from '@/stores/atoms/stageAtom.js';
import { interactionAtom } from '@/stores/atoms/interactionAtom.js';

let wired = false;

export default function wireAtomicToBeatBus() {
  if (wired) return; wired = true;

  // Stage changes → orchestra + nudge build
  let prevStage = stageAtom.getState().currentStage;
  stageAtom.subscribe((s) => {
    const next = s.currentStage;
    if (next !== prevStage) {
      BeatBus.emit?.(EVENTS.STAGE_CHANGED, { from: prevStage, to: next, reason: 'atom' });
      BeatBus.emit?.(EVENTS.BUILD_BLUEPRINT, { stage: next, trigger: 'stage-change' });
      prevStage = next;
    }
  });

  // Morph progress → orchestra
  let lastMorph = Number(interactionAtom.getState()?.morphProgress ?? 0);
  interactionAtom.subscribe((s) => {
    const v = Number(s.morphProgress ?? 0);
    if (v !== lastMorph) {
      BeatBus.emit?.(EVENTS.MORPH_PROGRESS, { value: Math.max(0, Math.min(1, v)) });
      lastMorph = v;
    }
  });
}
`;
  writeFileBacked(file, content, 'bridge');
}

/* 2) Interaction morph shim */
function ensureInteractionMorphShim() {
  const file = path.join(CWD, 'src/stores/atoms/_interactionMorphShim.js');
  const content =
`// AUTO-GENERATED by HOT-DORS Bridge — ensures morphProgress field + helper
import { interactionAtom } from './interactionAtom.js';

try {
  const s = interactionAtom.getState ? interactionAtom.getState() : {};
  if (typeof s.morphProgress !== 'number') {
    interactionAtom.setState?.({ morphProgress: 0 });
  }
  if (!interactionAtom.setMorph) {
    interactionAtom.setMorph = (v) => {
      const clamped = Math.max(0, Math.min(1, Number(v)||0));
      interactionAtom.setState?.({ morphProgress: clamped });
    };
  }
} catch (e) {
  console.warn('interactionMorphShim: could not ensure morph fields', e);
}
`;
  writeFileBacked(file, content, 'shim');
}

/* 3) Global scroll→morph sync bootstrap */
function ensureMorphSyncBootstrap() {
  const file = path.join(CWD, 'src/bootstrap/morph-sync.js');
  const content =
`// AUTO-GENERATED by HOT-DORS Bridge — global scroll → interactionAtom.morphProgress
import { interactionAtom } from '@/stores/atoms/interactionAtom.js';

let rafPending = false;
function onScroll() {
  if (rafPending) return; rafPending = true;
  requestAnimationFrame(() => {
    try {
      const scrollTop = window.scrollY;
      const scrollHeight = Math.max(document.documentElement.scrollHeight - window.innerHeight, 1);
      const progress = Math.min(scrollTop / scrollHeight, 1);
      const morph = Math.min(progress * 2, 1);
      interactionAtom.setMorph?.(morph);
    } finally {
      rafPending = false;
    }
  });
}

window.addEventListener('scroll', onScroll, { passive: true });
onScroll();
`;
  writeFileBacked(file, content, 'bootstrap');
}

/* 4) StateCore init (idempotent) */
function ensureStateCoreInit() {
  const file = path.join(CWD, 'modules/state/index.js');
  const existing = read(file) || '';
  const wanted =
`// AUTO-GENERATED/UPDATED by HOT-DORS Bridge — StateCore index
import wireAtomicToBeatBus from './bridges/AtomicToBeatBus.js';

export async function initStateCore({ enableEventValidation = false } = {}) {
  if (globalThis.__STATE_CORE_READY__) return true;
  try {
    wireAtomicToBeatBus();

    try { await import('@/stores/atoms/_interactionMorphShim.js'); }
    catch (e) { console.warn('StateCore: morph shim missing (ok)', e?.message||e); }

    if (enableEventValidation) {
      const { default: EventValidator } = await import('@/modules/orchestration/core/EventValidator.js');
      EventValidator.initialize({ strict: true });
    }
    globalThis.__STATE_CORE_READY__ = true;
    console.log('🧭 StateCore: initialized');
    return true;
  } catch (e) {
    console.error('🧭 StateCore: init failed', e);
    return false;
  }
}

export default { initStateCore };
`;
  if (!existing.trim()) return writeFileBacked(file, wanted, 'state-index');
  if (!/export\s+async\s+function\s+initStateCore/.test(existing)) {
    const merged = existing.trimEnd() + '\n\n' + wanted;
    return writeFileBacked(file, merged, 'state-index-append');
  }
  if (!/from\s+['"]\.\/bridges\/AtomicToBeatBus\.js['"]/.test(existing)) {
    const withImport = `import wireAtomicToBeatBus from './bridges/AtomicToBeatBus.js';\n` + existing;
    return writeFileBacked(file, withImport, 'state-index-import');
  }
  report.skipped.push(file);
}

/* 5) EventValidator (no hooks) */
function ensureEventValidator() {
  const file = path.join(CWD, 'modules/orchestration/core/EventValidator.js');
  const content =
`// AUTO-GENERATED by HOT-DORS Bridge — EventValidator (no React hooks)
import BeatBus from '@/theater/bus';
import { EVENTS } from '@/theater/events.js';

class EventValidator {
  static initialize({ strict = false } = {}) {
    if (this._ready) return; this._ready = true;
    this._off = [
      BeatBus.on?.(EVENTS.STAGE_CHANGED, (p)=> this._validate('STAGE_CHANGED', p, strict)),
      BeatBus.on?.(EVENTS.MORPH_PROGRESS,(p)=> this._validate('MORPH_PROGRESS', p, strict)),
      BeatBus.on?.(EVENTS.BUILD_BLUEPRINT,(p)=> this._validate('BUILD_BLUEPRINT', p, strict)),
    ].filter(Boolean);
    console.log('🔎 EventValidator ready');
  }
  static dispose(){ (this._off||[]).forEach(off=>off&&off()); this._off=[]; this._ready=false; }
  static _validate(evt, payload, strict){
    if (evt==='MORPH_PROGRESS' && (typeof payload?.value!=='number' || payload.value<0 || payload.value>1)) {
      console.warn('EV BAD morph', payload); if (strict) throw new Error('Invalid morph payload');
    }
    if (evt==='STAGE_CHANGED' && !payload?.to) {
      console.warn('EV BAD stage', payload); if (strict) throw new Error('Invalid stage payload');
    }
  }
}
export default EventValidator;
`;
  writeFileBacked(file, content, 'validator');
}

/* 6) Patch src/main.jsx to init StateCore + morph sync */
function patchMainBootstrap() {
  const file = path.join(CWD, 'src/main.jsx');
  let s = read(file);
  if (!s) { report.errors.push({ file, error: 'not found' }); return; }
  let changed = false;

  if (!s.includes("initStateCore")) {
    s = `import { initStateCore } from '../modules/state/index.js';\n` + s;
    // place init after imports
    s = s.replace(/(^import .+\n)+/m, (m)=> m + `\ninitStateCore?.({ enableEventValidation: false });\n`);
    changed = true;
  }
  if (!s.includes(`import '@/bootstrap/morph-sync.js'`)) {
    s = s.replace(/(^import .+\n)+/m, (m)=> m + `import '@/bootstrap/morph-sync.js';\n`);
    changed = true;
  }
  if (changed) writeFileBacked(file, s, 'bootstrap-main');
  else report.skipped.push(file);
}

/* 7) Atoms Doctor */
function ensureAtomsDoctor() {
  const file = path.join(CWD, 'scripts/atoms-doctor.cjs');
  const content =
`#!/usr/bin/env node
const fs=require('fs'),path=require('path'); const CWD=process.cwd();
const OUT_DIR=path.join(CWD,'doctor_artifacts'); fs.mkdirSync(OUT_DIR,{recursive:true});
const OUT_JSON=path.join(OUT_DIR,'atoms-report.json'); const OUT_MD=path.join(OUT_DIR,'atoms-summary.md');

const files=[];
function walk(d){ for(const e of fs.readdirSync(d,{withFileTypes:true})) {
  const p=path.join(d,e.name);
  if(e.isDirectory()) walk(p);
  else if(/\\.(j|t)sx?$/.test(p)) files.push(p);
}}
['src','modules'].forEach(d=>fs.existsSync(d)&&walk(d));

const atoms=[], seenById=new Map();
for (const f of files) {
  const s=fs.readFileSync(f,'utf8');
  const re=/createAtom\\(\\s*['"\`]([\\w-]+)['"\`]\\s*,\\s*\\{/g;
  let m; while((m=re.exec(s))){
    const id=m[1];
    const rec={ id, file:f.replace(CWD+'/','') };
    atoms.push(rec);
    const arr=seenById.get(id)||[]; arr.push(rec.file); seenById.set(id,arr);
  }
}
const duplicates=[...seenById.entries()].filter(([,files])=>files.length>1)
  .map(([id,files])=>({id,files}));
const report={ count:atoms.length, duplicates, atoms };

fs.writeFileSync(OUT_JSON, JSON.stringify(report,null,2));
fs.writeFileSync(OUT_MD, [
  '# Atoms Doctor',
  \`Total: \${atoms.length}\`,
  duplicates.length?('## Duplicates\\n'+duplicates.map(d=>\`- \${d.id}\\n  \${d.files.join('\\n  ')}\`).join('\\n')):'## No duplicates',
].join('\\n\\n'));
console.log('Atoms Doctor written:\\n -', OUT_JSON,'\\n -',OUT_MD);
`;
  writeFileBacked(file, content, 'doctor');
  try { fs.chmodSync(file, 0o755); } catch {}
}

