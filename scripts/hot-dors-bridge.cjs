/* 9) package.json scripts */
function patchPackageJson() {
  const pjPath = path.join(CWD, 'package.json');
  let pkg = {};
  try { pkg = JSON.parse(fs.readFileSync(pjPath,'utf8')); } catch { report.errors.push({ file: 'package.json', error: 'parse failed' }); return; }
  pkg.scripts = pkg.scripts || {};
  if (!pkg.scripts['hot-dors:bridge']) pkg.scripts['hot-dors:bridge'] = 'node scripts/hot-dors-bridge.cjs';
  if (!pkg.scripts['doctor:atoms'])    pkg.scripts['doctor:atoms']    = 'node scripts/atoms-doctor.cjs';
  if (!pkg.scripts['doctor:all'])      pkg.scripts['doctor:all']      = 'npm -s run doctor:imports && npm -s run doctor:atoms && npm -s run doctor:render && npm -s run hot-dors';
  writeFileBacked(pjPath, JSON.stringify(pkg,null,2) + '\n', 'package.json');
}

/* run all */
try {
  ensureAtomicToBeatBus();
  ensureInteractionMorphShim();
  ensureMorphSyncBootstrap();
  ensureStateCoreInit();
  ensureEventValidator();
  patchMainBootstrap();
  ensureAtomsDoctor();
  ensureSprintRecorder();
  patchPackageJson();
} catch (e) {
  report.errors.push({ error: e?.stack || String(e) });
}

const outJson = path.join(OUT_DIR, 'hot-dors-bridge-report.json');
fs.writeFileSync(outJson, JSON.stringify(report,null,2));
const outMd = path.join(OUT_DIR, 'hot-dors-bridge-summary.md');
fs.writeFileSync(outMd, [
  '# HOT-DORS Bridge Summary',
  `Changed: ${report.changed.length}`,
  `Created: ${report.created.length}`,
  `Skipped: ${report.skipped.length}`,
  report.errors.length?('## Errors\\n'+report.errors.map(e=>'- '+JSON.stringify(e)).join('\\n')):'## No errors',
].join('\\n\\n'));

console.log('HOT-DORS Bridge complete.');
console.log('Artifacts:');
console.log(' -', outJson);
console.log(' -', outMd);
